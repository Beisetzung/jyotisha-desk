import { setup, readJhd } from './common.mjs';
import { parseJHD } from '../src/jhd.js';
import * as A from '../src/astro.js';
import * as E from '../src/eclipse.js';
import * as TX from '../src/transitx.js';
import * as V from '../src/varsha.js';
import { allYogas } from '../src/yogas2.js';
import * as J from '../src/jaimini.js';
import * as swe from '../src/swe.js';
await setup();
const ch = A.computeChart(parseJHD(readJhd('Mahatma Gandhi.jhd'), 'g'));
const t = (n, f) => { const s = Date.now(); const r = f(); console.log(n.padEnd(34), Date.now() - s, 'ms'); return r; };
const jd0 = swe.julday(1869, 10, 2, 0);
const ecl = t('eclipses 100 y (with natal+local)', () => E.listEclipses(jd0, jd0 + 100 * 365.25, { natal: ch, loc: { lon: 69.8, lat: 21.6, alt: 0 }, limit: 600 }));
console.log('  count', ecl.length, 'sol', ecl.filter((e) => e.kind === 'sol').length, 'lun', ecl.filter((e) => e.kind === 'lun').length);
t('events 10 y, 7 planets', () => TX.findEvents(jd0, jd0 + 10 * 365.25, [0, 2, 3, 4, 5, 6, 7], A.DEFAULT_SETTINGS));
t('events 40 y, 7 planets', () => TX.findEvents(jd0, jd0 + 40 * 365.25, [0, 2, 3, 4, 5, 6, 7], A.DEFAULT_SETTINGS));
t('saturn phases 100 y', () => TX.saturnPhases(ch, ch.jd + 100 * 365.25));
t('varsha table 100 y', () => V.varshaTable(ch, 1870, 1969, { lon: 69.8, lat: 21.6, tz: 4.65 }));
t('mudda', () => V.muddaDasha(ch, 1900, { lon: 69.8, lat: 21.6, tz: 4.65 }));
t('yogas', () => allYogas(ch));
t('chara', () => J.charaDasha(ch));
